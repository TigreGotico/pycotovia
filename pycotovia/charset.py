# Latin-1 character constants
a_acentuada = 0xE1  # á
e_acentuada = 0xE9  # é
i_acentuada = 0xED  # í
o_acentuada = 0xF3  # ó
u_acentuada = 0xFA  # ú
u_con_dierese = 0xFC  # ü
i_con_dierese = 0xEF  # ï
e_con_dierese = 0xEB  # ë
enne_minuscula = 0xF1  # ñ
cedilla_minuscula = 0xE7  # ç

VOCAL_MINUSCULA_RARA = {
    0xE0, 0xE1, 0xE2, 0xE3, 0xE4, 0xE5, 0xE6,
    0xE8, 0xE9, 0xEA, 0xEB,
    0xEC, 0xED, 0xEE, 0xEF,
    0xF2, 0xF3, 0xF4, 0xF5, 0xF6, 0xF8,
    0xF9, 0xFA, 0xFB, 0xFC,
    0xFD, 0xFE, 0xFF,
}

VOCAL_MAIUSCULA_RARA = {
    0xC0, 0xC1, 0xC2, 0xC3, 0xC4, 0xC5, 0xC6,
    0xC8, 0xC9, 0xCA, 0xCB,
    0xCC, 0xCD, 0xCE, 0xCF,
    0xD2, 0xD3, 0xD4, 0xD5, 0xD6, 0xD8,
    0xD9, 0xDA, 0xDB, 0xDC,
    0xDD, 0xDE,
}

_to_minuscula = list(range(256))
for i in range(65, 91):
    _to_minuscula[i] = i + 32
EXTENDED_LOWER = {
    0xC0: 0xE0, 0xC1: 0xE1, 0xC2: 0xE2, 0xC3: 0xE3,
    0xC4: 0xE4, 0xC5: 0xE5, 0xC6: 0xE6,
    0xC7: 0xE7, 0xC8: 0xE8, 0xC9: 0xE9, 0xCA: 0xEA,
    0xCB: 0xEB, 0xCC: 0xEC, 0xCD: 0xED, 0xCE: 0xEE,
    0xCF: 0xEF, 0xD1: 0xF1, 0xD2: 0xF2, 0xD3: 0xF3,
    0xD4: 0xF4, 0xD5: 0xF5, 0xD6: 0xF6, 0xD8: 0xF8,
    0xD9: 0xF9, 0xDA: 0xFA, 0xDB: 0xFB, 0xDC: 0xFC,
    0xDD: 0xFD, 0xDE: 0xFE, 0xDF: 0xDF,
}
for k, v in EXTENDED_LOWER.items():
    _to_minuscula[k] = v


def to_minuscula(b: int) -> int:
    return _to_minuscula[b & 0xFF]


def to_minusculas(s: str) -> str:
    return "".join(chr(to_minuscula(ord(c))) for c in s)


def vocal_minuscula_acentuada(c: str) -> bool:
    return ord(c) in (a_acentuada, e_acentuada, i_acentuada, o_acentuada, u_acentuada)


def vocal_maiuscula_acentuada(c: str) -> bool:
    b = ord(c)
    return b in (0xC1, 0xC9, 0xCD, 0xD3, 0xDA)


def vocal_acentuada(c: str) -> bool:
    return vocal_minuscula_acentuada(c) or vocal_maiuscula_acentuada(c)


_VOCAL_SET = {
    0x41, 0x45, 0x49, 0x4F, 0x55,
    0x61, 0x65, 0x69, 0x6F, 0x75,
    a_acentuada, e_acentuada, i_acentuada, o_acentuada, u_acentuada,
    0xC1, 0xC9, 0xCD, 0xD3, 0xDA,
    0xDC, 0xFC, 0xCF, 0xEF, 0xCB, 0xEB,
}
_VOCAL_SET.update(VOCAL_MINUSCULA_RARA)
_VOCAL_SET.update(VOCAL_MAIUSCULA_RARA)


def vocal(c: str) -> bool:
    return ord(c) in _VOCAL_SET


def letra(c: str) -> bool:
    b = ord(c)
    return (65 <= b <= 90) or (97 <= b <= 122) or b in _VOCAL_SET or b in (
        0xF1, 0xD1, 0xE7, 0xC7
    )


def consonante(c: str) -> bool:
    return letra(c) and not vocal(c)


def vocal_feble(c: str) -> bool:
    b = ord(c)
    return b in (0x49, 0x55, 0x69, 0x75, 0xDC, 0xFC)


def vocal_aberta(c: str) -> bool:
    b = ord(c)
    return b in (0x41, 0x61, 0x45, 0x65, 0x4F, 0x6F,
                 0xC1, 0xE1, 0xC9, 0xE9, 0xD3, 0xF3)


def es_diptongo(v1: str, v2: str) -> bool:
    if vocal_feble(v1):
        return True
    if vocal_aberta(v1) and vocal_feble(v2):
        return True
    return False


def es_triptongo(v1: str, v2: str, v3: str) -> bool:
    if vocal_feble(v1) and vocal_aberta(v2) and vocal_feble(v3):
        return True
    if ord(v2) in (0x69, 0x49) and vocal_aberta(v3):
        return True
    return False


